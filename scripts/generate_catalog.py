"""Regenerate the offline catalog imports; --check refuses stale output."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    names = json.loads((ROOT / "catalog_entries.json").read_text())
    if (
        not isinstance(names, list)
        or not all(isinstance(name, str) and name.isidentifier() for name in names)
        or len(set(names)) != len(names)
    ):
        raise ValueError("Catalog entries must be distinct Python identifiers")
    generated = (
        '"""Built-in names. Generated by scripts/generate_catalog.py; do not edit."""\n\n'
        "from .integrations import Catalog\n\n"
        + "\n".join(f'{name} = Catalog("{name}")' for name in names)
        + "\n\n__all__ = " + repr(names) + "\n"
    )
    target = ROOT / "src/avalanche/catalog.py"
    if args.check:
        if not target.exists() or target.read_text() != generated:
            parser.exit(1, "Catalog imports are stale. Run scripts/generate_catalog.py.\n")
    else:
        target.write_text(generated)


if __name__ == "__main__":
    main()
