"""Generate browser run semantics from avalanche.run_status (make web-proto)."""

from __future__ import annotations

import json
from pathlib import Path

from avalanche import run_status as status

TARGET = Path(__file__).resolve().parents[1] / "web/operator/src/runStatus.ts"


def main() -> None:
    constants = {
        "HUMAN_STATUSES": status.HUMAN_STATUSES,
        "LIVE_STATUSES": sorted(status.LIVE_STATUSES),
        "TERMINAL_STATUSES": sorted(status.TERMINAL_STATUSES),
        "WAITING_ON_SLOTS": status.WAITING_ON_SLOTS,
        "LOCAL_STATUS_MAP": status.LOCAL_STATUS_MAP,
        "LIFECYCLE_STATUS_MAP": status.LIFECYCLE_STATUS_MAP,
        "ERROR_TEMPLATES": status.ERROR_TEMPLATES,
    }
    body = "// Generated by scripts/export_run_status.py; edit avalanche/run_status.py.\n"
    for name, value in constants.items():
        body += f"export const {name} = {json.dumps(value, indent=2)} as const;\n"
    body += """
export type HumanStatus = (typeof HUMAN_STATUSES)[number];
export type WaitingOn = readonly [number, number, number, number, number];

export function humanStatus(lifecycle: keyof typeof LIFECYCLE_STATUS_MAP,
                            active: number, openWaits: number): HumanStatus {
  return lifecycle === "admitted" && openWaits > 0 && active === 0
    ? "waiting" : LIFECYCLE_STATUS_MAP[lifecycle];
}
export function localHumanStatus(raw: keyof typeof LOCAL_STATUS_MAP,
                                 openWaits: number, runningOutsideWait: number): HumanStatus {
  return raw === "running" && openWaits > 0 && runningOutsideWait === 0
    ? "waiting" : LOCAL_STATUS_MAP[raw];
}
export function runStatusLive(status: string | undefined): boolean {
  return LIVE_STATUSES.some(value => value === status);
}
export function runStatusTerminal(status: string | undefined): boolean {
  return TERMINAL_STATUSES.some(value => value === status);
}
export function waitingOnLabel(counts: WaitingOn | undefined): string {
  if (!counts) return "";
  const total = counts.reduce((sum, count) => sum + count, 0);
  if (!total) return "";
  const first = WAITING_ON_SLOTS[counts.findIndex(count => count > 0)];
  return `waiting on ${first}${total > 1 ? ` +${total - 1}` : ""}`;
}
const shortBytes = (value: string, limit: number): string =>
  new TextDecoder("utf-8", { fatal: false })
    .decode(new TextEncoder().encode(value).slice(0, limit))
    .replace(/\\uFFFD$/, "");
export function errorMessage(code: string, step?: string,
                             errorType?: string, reason = "step_failed"): string {
  let template: string = Object.hasOwn(ERROR_TEMPLATES, code)
    ? ERROR_TEMPLATES[code as keyof typeof ERROR_TEMPLATES] : ERROR_TEMPLATES.unknown;
  if (code === "node_failed") {
    if (reason === "node_timeout") template = ERROR_TEMPLATES.node_timeout;
    else if (errorType
      && /^[A-Za-z_][A-Za-z0-9_.]{0,63}$/.exec(errorType)?.[0] === errorType)
      template = ERROR_TEMPLATES.node_failed_type;
  } else if (code === "wait_expired" && step !== undefined)
    template = ERROR_TEMPLATES.wait_expired_step;
  return shortBytes(template.replace("{step}", shortBytes(step ?? "", 48))
    .replace("{error_type}", errorType ?? "").replace("{reason}", reason), 120);
}
"""
    TARGET.write_text(body)


if __name__ == "__main__":
    main()
